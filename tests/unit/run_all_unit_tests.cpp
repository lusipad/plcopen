int main(int argc, char* argv[]) {
    // Parse command line arguments
    bool verbose = false;
    bool quiet = false;
    
    for (int i = 1; i < argc; i++) {
        std::string arg = argv[i];
        if (arg == "--verbose" || arg == "-v") {
            verbose = true;
        } else if (arg == "--quiet" || arg == "-q") {
            quiet = true;
        } else if (arg == "--help" || arg == "-h") {
            std::cout << "PLCOpen Unit Test Runner" << std::endl;
            std::cout << "Usage: " << argv[0] << " [OPTIONS]" << std::endl;
            std::cout << "Options:" << std::endl;
            std::cout << "  -v, --verbose    Verbose output" << std::endl;
            std::cout << "  -q, --quiet      Quiet output" << std::endl;
            std::cout << "  -h, --help       Show this help message" << std::endl;
            std::cout << std::endl;
            std::cout << "Environment Variables:" << std::endl;
            std::cout << "  ENABLE_COVERAGE  Generate coverage report" << std::endl;
            return 0;
        }
    }
    
    // Disable colors if not running in a terminal or if quiet mode
    if (quiet || !isatty(STDOUT_FILENO)) {
        Colors::RESET = Colors::RED = Colors::GREEN = Colors::YELLOW = 
        Colors::BLUE = Colors::MAGENTA = Colors::CYAN = Colors::WHITE = "";
    }
    
    UnitTestRunner runner;
    
    try {
        runner.runAllTests();
    } catch (const std::exception& e) {
        std::cout << Colors::RED << "Fatal error running tests: " << e.what() << Colors::RESET << std::endl;
        return 1;
    } catch (...) {
        std::cout << Colors::RED << "Unknown fatal error running tests" << Colors::RESET << std::endl;
        return 1;
    }
    
    return runner.getExitCode();
}