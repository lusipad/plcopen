// ANSI color codes for console output
namespace Colors {
    const std::string RESET = "\033[0m";
    const std::string RED = "\033[31m";
    const std::string GREEN = "\033[32m";
    const std::string YELLOW = "\033[33m";
    const std::string BLUE = "\033[34m";
    const std::string MAGENTA = "\033[35m";
    const std::string CYAN = "\033[36m";
    const std::string WHITE = "\033[37m";
}

class UnitTestRunner {
public:
    struct TestSuiteResult {
        std::string name;
        bool passed;
        int testCount;
        int passedCount;
        int failedCount;
        std::chrono::milliseconds duration;
        std::string errorMessage;
    };

    void runAllTests() {
        std::cout << Colors::CYAN << "========================================" << Colors::RESET << std::endl;
        std::cout << Colors::CYAN << "  PLCOpen Unit Test Suite Runner" << Colors::RESET << std::endl;
        std::cout << Colors::CYAN << "  Generated by Test Enhancement Initiative" << Colors::RESET << std::endl;
        std::cout << Colors::CYAN << "========================================" << Colors::RESET << std::endl;
        std::cout << std::endl;
        
        auto overallStart = std::chrono::steady_clock::now();
        
        // Run all test suites
        results_.push_back(runTestSuite("Real Time Scheduler", run_scheduler_tests));
        results_.push_back(runTestSuite("Memory Management", run_memory_tests));  
        results_.push_back(runTestSuite("Lockfree Data Structures", run_lockfree_tests));
        results_.push_back(runTestSuite("Error Handling", run_error_handler_tests));
        
        auto overallEnd = std::chrono::steady_clock::now();
        auto overallDuration = std::chrono::duration_cast<std::chrono::milliseconds>(overallEnd - overallStart);
        
        // Print summary
        printSummary(overallDuration);
        
        // Generate coverage report if enabled
        if (std::getenv("ENABLE_COVERAGE")) {
            generateCoverageReport();
        }
    }
    
    bool allTestsPassed() const {
        for (const auto& result : results_) {
            if (!result.passed) {
                return false;
            }
        }
        return true;
    }
    
    int getExitCode() const {
        return allTestsPassed() ? 0 : 1;
    }

private:
    std::vector<TestSuiteResult> results_;
    
    TestSuiteResult runTestSuite(const std::string& name, int (*testFunction)()) {
        std::cout << Colors::BLUE << "Running " << name << " Tests..." << Colors::RESET << std::endl;
        
        auto start = std::chrono::steady_clock::now();
        int result = 0;
        
        try {
            result = testFunction();
        } catch (const std::exception& e) {
            result = 1;
            std::cout << Colors::RED << "Exception in " << name << " tests: " << e.what() << Colors::RESET << std::endl;
        } catch (...) {
            result = 1;
            std::cout << Colors::RED << "Unknown exception in " << name << " tests" << Colors::RESET << std::endl;
        }
        
        auto end = std::chrono::steady_clock::now();
        auto duration = std::chrono::duration_cast<std::chrono::milliseconds>(end - start);
        
        TestSuiteResult suiteResult;
        suiteResult.name = name;
        suiteResult.passed = (result == 0);
        suiteResult.duration = duration;
        
        // Print result
        if (suiteResult.passed) {
            std::cout << Colors::GREEN << "✓ " << name << " Tests PASSED";
        } else {
            std::cout << Colors::RED << "✗ " << name << " Tests FAILED";
        }
        std::cout << " (" << duration.count() << "ms)" << Colors::RESET << std::endl;
        std::cout << std::endl;
        
        return suiteResult;
    }
    
    void printSummary(std::chrono::milliseconds totalDuration) {
        std::cout << Colors::CYAN << "========================================" << Colors::RESET << std::endl;
        std::cout << Colors::CYAN << "  Test Summary" << Colors::RESET << std::endl;
        std::cout << Colors::CYAN << "========================================" << Colors::RESET << std::endl;
        
        int totalSuites = results_.size();
        int passedSuites = 0;
        int failedSuites = 0;
        
        for (const auto& result : results_) {
            std::string status = result.passed ? 
                Colors::GREEN + "PASS" + Colors::RESET : 
                Colors::RED + "FAIL" + Colors::RESET;
            
            std::cout << "  " << result.name << ": " << status 
                      << " (" << result.duration.count() << "ms)" << std::endl;
            
            if (result.passed) {
                passedSuites++;
            } else {
                failedSuites++;
            }
        }
        
        std::cout << std::endl;
        std::cout << "Total Suites: " << totalSuites << std::endl;
        std::cout << Colors::GREEN << "Passed: " << passedSuites << Colors::RESET << std::endl;
        
        if (failedSuites > 0) {
            std::cout << Colors::RED << "Failed: " << failedSuites << Colors::RESET << std::endl;
        }
        
        std::cout << "Total Time: " << totalDuration.count() << "ms" << std::endl;
        
        double success_rate = totalSuites > 0 ? (static_cast<double>(passedSuites) / totalSuites * 100.0) : 0.0;
        std::cout << "Success Rate: " << std::fixed << std::setprecision(1) << success_rate << "%" << std::endl;
        
        std::cout << std::endl;
        
        if (allTestsPassed()) {
            std::cout << Colors::GREEN << "🎉 ALL TESTS PASSED!" << Colors::RESET << std::endl;
        } else {
            std::cout << Colors::RED << "❌ SOME TESTS FAILED!" << Colors::RESET << std::endl;
            std::cout << Colors::YELLOW << "Please check the test output above for details." << Colors::RESET << std::endl;
        }
        
        std::cout << std::endl;
    }
    
    void generateCoverageReport() {
        std::cout << Colors::MAGENTA << "Generating code coverage report..." << Colors::RESET << std::endl;
        
        // This would integrate with the coverage script we created earlier
        int result = system("./scripts/generate-coverage-report.sh");
        
        if (result == 0) {
            std::cout << Colors::GREEN << "Coverage report generated successfully!" << Colors::RESET << std::endl;
        } else {
            std::cout << Colors::YELLOW << "Warning: Coverage report generation failed or not available" << Colors::RESET << std::endl;
        }
    }
};

